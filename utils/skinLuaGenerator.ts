// GLua skin-file generator (Derma Skin Editor, Phase 4).
//
// Emits the SAFE copy-based pattern (knowledge/research_derma_skins.md §7/§10):
//   SKIN = table.Copy( derma.GetNamedSkin( "Default" ) )   -- every nested path populated
//   ...only the fields the user overrode, as literal Color(r,g,b,a)...
//   derma.DefineSkin( "<Name>", "<desc>", SKIN )
//
// Guarantees:
//  - Only overridden fields are emitted (sparse) — safe because table.Copy(Default)
//    pre-populates every nested table, so `SKIN.Colours.Button.Normal = ...` never
//    nil-indexes.
//  - NEVER emits a `tex` block or Paint methods in v1 (they inherit from Default).
//  - Name sanitized to [%w_]+ and never "Default" (that would replace the global skin).

import { SkinColor, SkinDef } from './skinTypes';
import { DEFAULT_SKIN_SCALARS } from './skinConstants';

const isSkinColor = (v: any): v is SkinColor =>
  v && typeof v === 'object' &&
  typeof v.r === 'number' && typeof v.g === 'number' &&
  typeof v.b === 'number' && typeof v.a === 'number';

const colorLua = (c: SkinColor): string =>
  `Color( ${c.r}, ${c.g}, ${c.b}, ${c.a} )`;

/** Escape a string for a double-quoted Lua literal. */
const luaStr = (s: string): string =>
  '"' + String(s ?? '').replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n') + '"';

/** Sanitize a skin name to a Lua-safe identifier; never "Default". */
export const sanitizeLuaSkinName = (raw: string): string => {
  let name = (raw || '').replace(/[^A-Za-z0-9_]/g, '');
  if (!name) name = 'MySkin';
  if (/^\d/.test(name)) name = 'S' + name;
  if (name.toLowerCase() === 'default') name = name + '_1';
  return name;
};

/** Recursively emit `SKIN.Colours.<path> = Color(...)` for every overridden leaf. */
const emitColours = (node: any, path: string[], out: string[]): void => {
  if (!node || typeof node !== 'object') return;
  for (const key of Object.keys(node)) {
    const val = node[key];
    if (isSkinColor(val)) {
      out.push(`SKIN.Colours.${[...path, key].join('.')} = ${colorLua(val)}`);
    } else if (val && typeof val === 'object') {
      emitColours(val, [...path, key], out);
    }
  }
};

export const generateSkinLua = (def: SkinDef): string => {
  const name = sanitizeLuaSkinName(def.name);
  const desc = def.printName || name;

  const lines: string[] = [];
  lines.push('-- Generated by DermaGen AI — Derma Skin');
  lines.push(`-- Drop this file in: garrysmod/lua/skins/${name}.lua`);
  lines.push('-- (auto-loads clientside; apply with panel:SetSkin("' + name + '"))');
  lines.push('');
  lines.push('-- Copy-based strategy: every nested Colours/tex path is pre-populated,');
  lines.push('-- so the sparse overrides below can never nil-index (research §7).');
  lines.push('local SKIN = table.Copy( derma.GetNamedSkin( "Default" ) )');
  lines.push('');

  // Metadata (always emitted).
  lines.push(`SKIN.PrintName    = ${luaStr(def.printName || name)}`);
  lines.push(`SKIN.Author       = ${luaStr(def.author || '')}`);
  lines.push(`SKIN.DermaVersion = ${Number.isFinite(def.dermaVersion) ? def.dermaVersion : 1}`);

  // Fonts (only if overridden).
  const fonts: [string, string | undefined][] = [
    ['fontFrame', def.fontFrame],
    ['fontTab', def.fontTab],
    ['fontCategoryHeader', def.fontCategoryHeader],
  ];
  const fontLines = fonts.filter(([, v]) => v).map(([k, v]) => `SKIN.${k} = ${luaStr(v!)}`);
  if (fontLines.length) {
    lines.push('');
    lines.push('-- Fonts');
    lines.push(...fontLines);
  }

  // GwenTexture (advanced/export-only; inert for inherited tex but harmless).
  if (def.gwenTexture) {
    lines.push('');
    lines.push(`SKIN.GwenTexture = Material( ${luaStr(def.gwenTexture)} )`);
  }

  // Scalar colours (only overridden keys, emitted in canonical §3 order).
  const scalarLines: string[] = [];
  for (const key of Object.keys(DEFAULT_SKIN_SCALARS) as (keyof typeof DEFAULT_SKIN_SCALARS)[]) {
    const v = def.scalars[key];
    if (v) scalarLines.push(`SKIN.${key} = ${colorLua(v)}`);
  }
  if (scalarLines.length) {
    lines.push('');
    lines.push('-- Scalar colours');
    lines.push(...scalarLines);
  }

  // Colours tree (literal Color() per overridden leaf).
  const colourLines: string[] = [];
  emitColours(def.colours, [], colourLines);
  if (colourLines.length) {
    lines.push('');
    lines.push('-- Colours tree (literal Color() leaves; parent tables exist via table.Copy)');
    lines.push(...colourLines.sort());
  }

  lines.push('');
  lines.push(`derma.DefineSkin( ${luaStr(name)}, ${luaStr(desc)}, SKIN )`);
  lines.push('');

  return lines.join('\n');
};
